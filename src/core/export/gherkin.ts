import { orderScenarios } from '../scenarios';
import type { ExportData } from '../types';

const inline = (s: string) => s.replace(/\r?\n|\r/g, ' ');

/** `scenarios.feature` (SPEC §11.3). */
export function toGherkin(data: ExportData): string {
  const { machine } = data;
  const blocks = orderScenarios(data.scenarios, machine).map((s) =>
    [
      `  @priority-${s.priority} @${s.origin}`,
      `  Scenario: ${inline(s.title)}`,
      ...s.steps.map((step) => `    ${step.keyword} ${inline(step.text)}`),
    ].join('\n'),
  );
  const head = [
    `Feature: ${inline(machine.name)}`,
    `  Generated by RealityCompiler on ${data.generatedAt}. Flow type: ${machine.flowType}.`,
  ].join('\n');
  return [head, ...blocks].join('\n\n') + '\n';
}
