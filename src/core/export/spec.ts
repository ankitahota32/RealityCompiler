import { toMermaid } from '../mermaid';
import { orderScenarios } from '../scenarios';
import type { ExportData, Finding } from '../types';

/** Model and user text on one line. */
const inline = (s: string) => s.replace(/\r?\n|\r/g, ' ');
/** Markdown table cell: one line, `|` escaped (SPEC §11.2). */
const cell = (s: string) => inline(s).replace(/\|/g, '\\|');
const yesNo = (b: boolean) => (b ? 'Yes' : 'No');
const row = (cells: string[]) => `| ${cells.map(cell).join(' | ')} |`;
const header = (cells: string[]) => [row(cells), `|${cells.map(() => '---').join('|')}|`];
const listOr = (items: string[], empty: string) => (items.length > 0 ? items : [empty]);

/** `spec.md` (SPEC §11.2). */
export function toSpecMarkdown(data: ExportData): string {
  const { machine } = data;
  const stateLabel = (id: string) => machine.states.find((s) => s.id === id)?.label ?? id;
  const eventLabel = (id: string) => machine.events.find((e) => e.id === id)?.label ?? id;
  const accepted = new Set(data.acceptedFindingIds);
  const open = data.remainingFindings.filter((f) => !accepted.has(f.id));
  const count = (sev: Finding['severity']) => open.filter((f) => f.severity === sev).length;
  const known = new Map<string, Finding>();
  for (const f of [...data.findings, ...data.remainingFindings]) if (!known.has(f.id)) known.set(f.id, f);
  const scenarios = orderScenarios(data.scenarios, machine);

  const lines: string[] = [
    `# ${inline(machine.name)} — Specification`,
    '',
    `Generated by RealityCompiler on ${data.generatedAt}. Flow type: ${machine.flowType}.`,
    '',
    '## 1. Summary',
    '',
    `- States: ${machine.states.length} · Events: ${machine.events.length} · Transitions: ${machine.transitions.length}`,
    `- Open issues: ${count('high')} high, ${count('medium')} medium, ${count('low')} low · Accepted as-is: ${data.acceptedFindingIds.length} · Resolved: ${data.resolvedFindingIds.length}`,
    '',
    '## 2. Flow diagram',
    '',
    '```mermaid',
    toMermaid(machine),
    '```',
    '',
    '## 3. States',
    '',
    ...header(['Id', 'Label', 'Start', 'End', 'Waits for outside', 'Needs user input', 'Evidence']),
    ...machine.states.map((s) =>
      row([s.id, s.label, yesNo(s.initial), s.terminal, yesNo(s.awaitsExternal), yesNo(s.userInput), s.evidence]),
    ),
    '',
    '## 4. Events',
    '',
    ...header(['Id', 'Label', 'Kind', 'Evidence']),
    ...machine.events.map((e) => row([e.id, e.label, e.kind, e.evidence])),
    '',
    '## 5. Transitions',
    '',
    ...header(['Id', 'From', 'Event', 'To']),
    ...machine.transitions.map((t) => row([t.id, stateLabel(t.from), eventLabel(t.event), stateLabel(t.to)])),
    '',
    '## 6. Business rules',
    '',
    ...listOr(
      data.rules.map((r) => `- ${r.id}: ${inline(r.text)} (decisions: ${r.findingIds.join(', ')})`),
      'No decisions were made yet.',
    ),
    '',
    '## 7. Decisions and assumptions',
    '',
    '### Decisions',
    '',
    ...listOr(
      data.decisions
        .filter((d) => d.answerType === 'option' || d.answerType === 'custom')
        .map((d) => {
          const f = known.get(d.findingId);
          return `- ${inline(f?.title ?? d.findingId)} — ${inline(f?.question.text ?? '')} — Answer: ${inline(d.answer)}`;
        }),
      'None.',
    ),
    '',
    '### Assumptions',
    '',
    ...listOr(data.assumptions.map((a) => `- ${inline(a)}`), 'None.'),
    '',
    '## 8. Open and accepted issues',
    '',
    ...listOr(
      data.remainingFindings.map(
        (f) =>
          `- [${f.severity.toUpperCase()}] ${inline(f.title)} — ${accepted.has(f.id) ? 'ACCEPTED AS-IS' : 'OPEN'} — ${inline(f.question.text)}`,
      ),
      'None.',
    ),
    '',
    '## 9. Scenarios',
    '',
    '### From decisions',
    '',
    ...listOr(scenarios.filter((s) => s.origin === 'decision').map((s) => `- ${inline(s.title)}`), 'None.'),
    '',
    '### Per transition',
    '',
    ...listOr(scenarios.filter((s) => s.origin === 'transition').map((s) => `- ${inline(s.title)}`), 'None.'),
    '',
    '## 10. Notes for implementers',
    '',
    '- Implement exactly the transitions in section 5. Behavior that is not listed is undefined: flag it, do not invent it.',
    '- Every item marked OPEN in section 8 must be resolved with the product owner before it is implemented.',
    '- Scenarios in section 9 describe behavior, not UI selectors.',
  ];
  return lines.join('\n') + '\n';
}
