import { orderScenarios } from '../scenarios';
import type { ExportData } from '../types';

const str = (s: string) => JSON.stringify(s);

/** `playwright-skeleton.spec.ts` (SPEC §11.4). Every string literal goes through JSON.stringify. */
export function toPlaywright(data: ExportData): string {
  const { machine } = data;
  const tests = orderScenarios(data.scenarios, machine).map((s) =>
    [
      `  test.fixme(${str(s.title)}, async ({ page }) => {`,
      ...s.steps.flatMap((step) => [
        `    await test.step(${str(`${step.keyword} ${step.text}`)}, async () => {`,
        '      // TODO: bind to the real app',
        '    });',
      ]),
      '  });',
    ].join('\n'),
  );
  return [
    "import { test } from '@playwright/test';",
    '',
    `// Generated by RealityCompiler on ${data.generatedAt}.`,
    '// These tests are SKELETONS: the app does not exist yet, so there are no real selectors.',
    '// Bind each step to your real UI, then remove test.fixme.',
    '',
    `test.describe(${str(machine.name)}, () => {`,
    tests.join('\n\n'),
    '});',
    '',
  ].join('\n');
}
